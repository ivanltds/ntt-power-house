// icon('star', { cls: 'on', title: 'Favorita' }) → <svg …>. Ícones decorativos ficam ocultos para leitores de tela.
export function icon(name, { size = 18, cls = '', title = '' } = {}) {
  const label = title ? ` role="img" aria-label="${title.replace(/"/g, '&quot;')}"><title>${title.replace(/</g, '&lt;')}</title` : ' aria-hidden="true"';
  return `<svg class="i i-${name} ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"${label}>${PATHS[name] ?? ''}</svg>`;
}

// Substitui <i data-icon="nome"></i> do HTML estático pelos SVGs.
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon, { size: Number(el.dataset.size ?? 18), cls: el.className });
  });
}
